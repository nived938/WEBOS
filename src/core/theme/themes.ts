export function exportThemeAsJSON(theme: ThemeDefinition): string {
  return JSON.stringify(theme, null, 2)
}

export function importThemeFromJSON(jsonStr: string): ThemeDefinition | null {
  try {
    const parsed = JSON.parse(jsonStr)
    if (!parsed || typeof parsed !== 'object') return null
    if (!parsed.name || typeof parsed.name !== 'string') return null

    const validAccents: AccentColor[] = ['blue', 'purple', 'emerald', 'orange', 'rose', 'amber']
    const accent: AccentColor = validAccents.includes(parsed.accentColor) ? parsed.accentColor : 'blue'

    return {
      id: 'custom-' + Date.now() + '-' + Math.random().toString(36).slice(2, 6),
      name: parsed.name.slice(0, 40),
      description: typeof parsed.description === 'string' ? parsed.description.slice(0, 160) : 'Custom imported theme',
      isBuiltIn: false,
      background: {
        wallpaperId: parsed.background?.wallpaperId || 'nova-aurora',
        type: parsed.background?.type || 'dynamic',
        fallbackColor: parsed.background?.fallbackColor || '#090919',
      },
      accentColor: accent,
      windowBackground: typeof parsed.windowBackground === 'string' ? parsed.windowBackground : 'rgba(16, 18, 27, 0.82)',
      panelAppearance: typeof parsed.panelAppearance === 'string' ? parsed.panelAppearance : 'rgba(12, 14, 20, 0.75)',
      dockAppearance: typeof parsed.dockAppearance === 'string' ? parsed.dockAppearance : 'rgba(15, 17, 26, 0.70)',
      borderColor: typeof parsed.borderColor === 'string' ? parsed.borderColor : 'rgba(255, 255, 255, 0.15)',
      textColor: typeof parsed.textColor === 'string' ? parsed.textColor : '#ffffff',
      buttonStyle: ['rounded', 'glass', 'pill', 'solid'].includes(parsed.buttonStyle) ? parsed.buttonStyle : 'glass',
      selectionColor: typeof parsed.selectionColor === 'string' ? parsed.selectionColor : '#3b82f6',
      highlightColor: typeof parsed.highlightColor === 'string' ? parsed.highlightColor : 'rgba(59, 130, 246, 0.35)',
      shadowIntensity: typeof parsed.shadowIntensity === 'number' ? Math.max(0, Math.min(100, parsed.shadowIntensity)) : 60,
      borderRadius: typeof parsed.borderRadius === 'number' ? Math.max(0, Math.min(32, parsed.borderRadius)) : 16,
      glassTransparency: typeof parsed.glassTransparency === 'number' ? Math.max(10, Math.min(90, parsed.glassTransparency)) : 30,
    }
  } catch {
    return null
  }
}

export function applyThemeCSS(theme: ThemeDefinition): void {
  if (typeof document === 'undefined') return
  const root = document.documentElement

  root.style.setProperty('--theme-window-bg', theme.windowBackground)
  root.style.setProperty('--theme-panel-bg', theme.panelAppearance)
  root.style.setProperty('--theme-dock-bg', theme.dockAppearance)
  root.style.setProperty('--theme-border-color', theme.borderColor)
  root.style.setProperty('--theme-text-color', theme.textColor)
  root.style.setProperty('--theme-selection-color', theme.selectionColor)
  root.style.setProperty('--theme-highlight-color', theme.highlightColor)
  root.style.setProperty('--theme-shadow-intensity', `${theme.shadowIntensity / 100}`)
  root.style.setProperty('--theme-radius', `${theme.borderRadius}px`)
  root.style.setProperty('--theme-glass-transparency', `${theme.glassTransparency / 100}`)
}
